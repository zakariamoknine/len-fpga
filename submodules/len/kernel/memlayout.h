#ifndef _LEN_MEMLAYOUT_H_
#define _LEN_MEMLAYOUT_H_

// len-fpga memory-map:
//
// [0x8000_0000 - 0x81FF_FFFF]: OpenSBI
// [0x8200_0000 - 0x85FF_FFFF]: General-Purpose RAM
// [0x8600_0000 - 0x87DF_FFFF]: RAM-based Filesystem
// [0x87E0_0000 - 0x87FF_FFFF]: VGA Framebuffeer

// UART
#define UART0 0x4A000000L
#define UART0_IRQ 2

// PLIC
#define PLIC 0x50000000L
#define PLIC_PRIORITY (PLIC + 0x0)
#define PLIC_PENDING (PLIC + 0x1000)
#define PLIC_SENABLE(hart) (PLIC + 0x2080 + (hart)*0x100)
#define PLIC_SPRIORITY(hart) (PLIC + 0x201000 + (hart)*0x2000)
#define PLIC_SCLAIM(hart) (PLIC + 0x201004 + (hart)*0x2000)

// CLINT
#define CLINT 0x5A000000L

// RAMFS region, 30 MiB
#define RAMFS_BASE 0x86000000L
#define RAMFS_SIZE 0x01E00000L

// FRAMEBUFFER region, 2 MiB
#define FRAMEBUFFER_BASE 0x87E00000L
#define FRAMEBUFFER_SIZE 0x00200000L

// KERNEL
#define KERNBASE 0x80200000L
#define PHYSTOP (KERNBASE + 94*1024*1024)

#define TRAMPOLINE (MAXVA - PGSIZE)

#define KSTACK(p) (TRAMPOLINE - ((p)+1)* 2*PGSIZE)

#define TRAPFRAME (TRAMPOLINE - PGSIZE)

// MMAP
#define MMAPBASE 0x40000000UL

#endif /* _LEN_MEMLAYOUT_H_ */
